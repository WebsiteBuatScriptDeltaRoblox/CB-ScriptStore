create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null check (username ~ '^[A-Za-z0-9_]{5,24}$'),
  avatar text not null default 'profile1.png',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.profiles add column if not exists avatar text not null default 'profile1.png';
create unique index if not exists profiles_username_lower_unique on public.profiles (lower(username));

do $$ begin
  if not exists (select 1 from pg_constraint where conname='profiles_avatar_check') then
    alter table public.profiles add constraint profiles_avatar_check check (avatar in ('profile1.png','profile2.png','profile3.png','profile4.png','profile5.png'));
  end if;
end $$;

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.profiles(id,username,avatar)
  values(new.id,coalesce(nullif(new.raw_user_meta_data->>'username',''),'user_'||substr(replace(new.id::text,'-',''),1,18)),coalesce(new.raw_user_meta_data->>'avatar','profile1.png'))
  on conflict(id) do update set username=excluded.username;
  return new;
end; $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

create table if not exists public.scripts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  filename text not null check (char_length(filename) between 1 and 120),
  code text not null default '' check (char_length(code) <= 500000),
  kind text not null default 'code',
  visibility text not null default 'private',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.scripts add column if not exists kind text not null default 'code';
alter table public.scripts add column if not exists visibility text not null default 'private';
alter table public.scripts add column if not exists code text not null default '';

do $$ begin
  if not exists (select 1 from pg_constraint where conname='scripts_kind_check') then
    alter table public.scripts add constraint scripts_kind_check check (kind in ('code','text'));
  end if;
  if not exists (select 1 from pg_constraint where conname='scripts_visibility_check') then
    alter table public.scripts add constraint scripts_visibility_check check (visibility in ('private','public'));
  end if;
end $$;
create index if not exists scripts_user_updated_idx on public.scripts(user_id,updated_at desc,id desc);

create or replace function public.enforce_script_limit()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  perform pg_advisory_xact_lock(hashtext(new.user_id::text));
  if (select count(*) from public.scripts where user_id=new.user_id) >= 50 then
    raise exception 'Maximum 50 scripts per account.' using errcode='P0001';
  end if;
  return new;
end; $$;

drop trigger if exists scripts_limit_50 on public.scripts;
create trigger scripts_limit_50 before insert on public.scripts for each row execute procedure public.enforce_script_limit();

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$ begin new.updated_at=now(); return new; end; $$;

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at before update on public.profiles for each row execute procedure public.set_updated_at();
drop trigger if exists scripts_set_updated_at on public.scripts;
create trigger scripts_set_updated_at before update on public.scripts for each row execute procedure public.set_updated_at();

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  message text not null check (char_length(message) between 1 and 500),
  created_at timestamptz not null default now()
);
create index if not exists chat_messages_created_idx on public.chat_messages(id desc);

create table if not exists public.presence (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  last_seen timestamptz not null default now()
);

-- Backfill profile rows for users created before this migration.
insert into public.profiles(id,username,avatar)
select u.id,coalesce(nullif(u.raw_user_meta_data->>'username',''),'user_'||substr(replace(u.id::text,'-',''),1,18)),coalesce(u.raw_user_meta_data->>'avatar','profile1.png')
from auth.users u
where not exists(select 1 from public.profiles p where p.id=u.id)
on conflict(id) do nothing;

-- Ensure the three user-owned tables relate to public.profiles, not auth.users.
do $$ declare r record; begin
  for r in select c.conrelid::regclass table_name,c.conname from pg_constraint c join pg_attribute a on a.attrelid=c.conrelid and a.attnum=any(c.conkey) where c.contype='f' and c.confrelid='auth.users'::regclass and a.attname='user_id' and c.conrelid in ('public.scripts'::regclass,'public.chat_messages'::regclass,'public.presence'::regclass) loop
    execute format('alter table %s drop constraint if exists %I',r.table_name,r.conname);
  end loop;
end $$;

alter table public.scripts drop constraint if exists scripts_user_id_profiles_fkey;
alter table public.scripts add constraint scripts_user_id_profiles_fkey foreign key(user_id) references public.profiles(id) on delete cascade;
alter table public.chat_messages drop constraint if exists chat_messages_user_id_profiles_fkey;
alter table public.chat_messages add constraint chat_messages_user_id_profiles_fkey foreign key(user_id) references public.profiles(id) on delete cascade;
alter table public.presence drop constraint if exists presence_user_id_profiles_fkey;
alter table public.presence add constraint presence_user_id_profiles_fkey foreign key(user_id) references public.profiles(id) on delete cascade;

alter table public.profiles enable row level security;
alter table public.scripts enable row level security;
alter table public.chat_messages enable row level security;
alter table public.presence enable row level security;

