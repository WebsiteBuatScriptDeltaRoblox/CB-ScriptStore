-- CB ScriptStore extended features
alter table public.scripts add column if not exists tags text default '';
alter table public.scripts add column if not exists view_count bigint default 0;
create index if not exists scripts_tags_idx on public.scripts(tags);
create unique index if not exists profiles_username_lower_idx on public.profiles(lower(username));

create table if not exists public.script_views(id bigint generated by default as identity primary key, script_id bigint references public.scripts(id) on delete cascade, user_id uuid references auth.users(id) on delete set null, visitor_id text, created_at timestamptz not null default now());
create index if not exists script_views_script_idx on public.script_views(script_id,created_at);

create table if not exists public.script_favorites(user_id uuid references auth.users(id) on delete cascade, script_id bigint references public.scripts(id) on delete cascade, created_at timestamptz not null default now(), primary key(user_id,script_id));

create table if not exists public.script_history(user_id uuid references auth.users(id) on delete cascade, script_id bigint references public.scripts(id) on delete cascade, last_viewed_at timestamptz not null default now(), primary key(user_id,script_id));

create table if not exists public.notifications(id bigint generated by default as identity primary key,user_id uuid references auth.users(id) on delete cascade,title text,message text,read_at timestamptz,created_at timestamptz not null default now());
create table if not exists public.script_reports(id bigint generated by default as identity primary key,script_id bigint references public.scripts(id) on delete cascade,reporter_id uuid references auth.users(id) on delete set null,reason text,created_at timestamptz not null default now());

alter table public.script_views enable row level security; alter table public.script_favorites enable row level security; alter table public.script_history enable row level security; alter table public.notifications enable row level security; alter table public.script_reports enable row level security;
drop policy if exists "public can record script views" on public.script_views; create policy "public can record script views" on public.script_views for insert to anon,authenticated with check (true);
drop policy if exists "users read own favorites" on public.script_favorites; create policy "users read own favorites" on public.script_favorites for select to authenticated using (auth.uid()=user_id);
drop policy if exists "users manage own favorites" on public.script_favorites; create policy "users manage own favorites" on public.script_favorites for all to authenticated using (auth.uid()=user_id) with check (auth.uid()=user_id);
drop policy if exists "users manage own history" on public.script_history; create policy "users manage own history" on public.script_history for all to authenticated using (auth.uid()=user_id) with check (auth.uid()=user_id);
drop policy if exists "users read own notifications" on public.notifications; create policy "users read own notifications" on public.notifications for select to authenticated using (auth.uid()=user_id);
drop policy if exists "users report scripts" on public.script_reports; create policy "users report scripts" on public.script_reports for insert to authenticated with check (auth.uid()=reporter_id);
-- Public scripts can be discovered without logging in.
drop policy if exists "public can read public scripts" on public.scripts; create policy "public can read public scripts" on public.scripts for select to anon,authenticated using (visibility='public' or auth.uid()=user_id);


create or replace function public.increment_script_view(p_script_id bigint) returns void language sql security definer set search_path=public as $$ update public.scripts set view_count=coalesce(view_count,0)+1 where id=p_script_id and visibility='public'; $$;
grant execute on function public.increment_script_view(bigint) to anon, authenticated;
